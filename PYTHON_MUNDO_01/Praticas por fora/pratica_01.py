# Peça dois números ao usuário e mostre
# o resultado das 4 operações básicas (+, -, *, /). 

n1 = int(input("Digite um número: "))
n2 = int(input("Digite outr número: "))
adicao = n1 + n2
subtracacao = n1 - n2
multiplicacao = n1 * n2
divisao = n1 / n2

print(f"""
Adiçao: {adicao}
Subtração: {subtracacao}
Multiplicação: {multiplicacao}
Divisão: {divisao}
""") 

